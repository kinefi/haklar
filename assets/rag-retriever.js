/**
- Client-side Hybrid RAG Retriever (BM25 Sparse + Concept Expansion + Fallback Text Matching)
- Reads `content/rag-index.json` generated by `scripts/build_rag_index.py`.
 */
(() => {
  let indexPromise = null;

  function normalize(value) {
    return String(value || "")
      .normalize("NFD")
      .replace(/\p{Diacritic}/gu, "")
      .replace(/ß/g, "ss")
      .replace(/ı/g, "i")
      .toLowerCase()
      .trim();
  }

  function tokenize(text) {
    return normalize(text)
      .split(/[^a-z0-9]+/)
      .filter((t) => t.length >= 2);
  }

  async function loadRagIndex(url = "content/rag-index.json") {
    if (!indexPromise) {
      indexPromise = fetch(new URL(url, document.baseURI))
        .then((res) => {
          if (!res.ok) throw new Error(`Could not load ${url}`);
          return res.json();
        })
        .catch((err) => {
          indexPromise = null;
          throw err;
        });
    }
    return indexPromise;
  }

  function expandConcepts(normalizedQuery, conceptsMap) {
    const matchedConcepts = new Set();
    const expandedTerms = new Set(tokenize(normalizedQuery));

    if (!conceptsMap) return { matchedConcepts, expandedTerms: [...expandedTerms] };

    for (const [conceptId, terms] of Object.entries(conceptsMap)) {
      if (!Array.isArray(terms)) continue;
      for (const term of terms) {
        const normTerm = normalize(term);
        // Doğrudan kelime veya alt dize eşleşmesi
        if (normalizedQuery === normTerm || normalizedQuery.includes(normTerm) || normTerm.includes(normalizedQuery)) {
          matchedConcepts.add(conceptId);
          terms.forEach((t) => {
            tokenize(t).forEach((tok) => expandedTerms.add(tok));
          });
          break;
        }
      }
    }
    return { matchedConcepts, expandedTerms: [...expandedTerms] };
  }

  async function retrieve(query, options = {}) {
    const {
      lang = null,
      sourceTypes = null,
      topK = 8,
      indexUrl = "content/rag-index.json"
    } = options;

    const index = await loadRagIndex(indexUrl);
    const normQuery = normalize(query);
    if (!normQuery) return [];

    const directTokens = tokenize(normQuery);
    const { matchedConcepts, expandedTerms } = expandConcepts(normQuery, index.concepts);

    const scored = [];
    for (const chunk of index.chunks || []) {
      if (sourceTypes && !sourceTypes.includes(chunk.sourceType)) continue;
      // Rehber kartlarını RAG alt listesinden hariç tut (onlar zaten üstte listeleniyor)
      if (chunk.sourceType === "guide_card") continue;

      let score = 0;
      const normText = normalize(chunk.text || "");
      const normTitle = normalize(chunk.title || "");

      // 1. TF-IDF / BM25 Sparse Eşleşmesi (Eğer tf varsa)
      if (chunk.tf) {
        for (const tok of directTokens) {
          if (chunk.tf[tok]) score += chunk.tf[tok] * 2.0;
        }
        for (const tok of expandedTerms) {
          if (chunk.tf[tok]) score += chunk.tf[tok] * 0.5;
        }
      }

      // 2. Doğrudan Metin / Başlık Taraması (Fallback & Güvence)
      for (const tok of directTokens) {
        if (tok.length >= 2) {
          if (normTitle.includes(tok)) score += 3.0;
          if (normText.includes(tok)) score += 1.0;
        }
      }

      // 3. Genişletilmiş Kavram Terimleri Taraması (Örn: "istifa" yazınca "kündigung" kelimesini metin içinde arar)
      for (const term of expandedTerms) {
        if (term.length >= 3) {
          if (normText.includes(term)) score += 2.5;
          if (normTitle.includes(term)) score += 4.0;
        }
      }

      // 4. Konsept Etiket Eşleşmesi
      if (chunk.concepts && Array.isArray(chunk.concepts)) {
        for (const c of chunk.concepts) {
          if (matchedConcepts.has(c)) score += 4.0;
        }
      }

      // 5. Tam Sorgu Eşleşmesi Bonusu
      if (normTitle.includes(normQuery) || normText.includes(normQuery)) {
        score += 5.0;
      }

      // Düşük eşik değeri ile alakalı tüm toplu sözleşme maddelerini yakala
      if (score > 0.05) {
        scored.push({
          ...chunk,
          score: Number(score.toFixed(3))
        });
      }
    }

    scored.sort((a, b) => b.score - a.score);
    return scored.slice(0, topK);
  }

  window.haklarRAG = {
    loadRagIndex,
    retrieve
  };
})();